# Tuples

# 1. Creating a tuple
fruits = ("Apple", "Banana", "Mango", "Orange")
print("Tuple:", fruits)

# 2. Accessing elements using indexing
print("First fruit:", fruits[0])
print("Second fruit:", fruits[1])

# 3. Tuple slicing
print("First three fruits:", fruits[0:3])

# 4. Finding the length
print("Length of tuple:", len(fruits))

# 5. Basic tuple operations
tuple1 = (1, 2, 3)
tuple2 = (4, 5, 6)

print("Concatenation:", tuple1 + tuple2)
print("Repetition:", tuple1 * 2)
print("Is 2 present?", 2 in tuple1)